#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import zlib from 'node:zlib';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const root=process.argv[2];
assert.ok(root,'Built snapshot path required');
const registry=JSON.parse(fs.readFileSync(`${root}/runtime/data/v9/source-registry.json`));
const source=registry.sources.find(s=>s.id==='allego-uk-pcpr-direct');
assert.equal(source.active,true);
assert.equal(source.optional,false);
assert.ok(source.path&&source.auditPath);
assert.equal(source.url,undefined);
const doc=JSON.parse(zlib.gunzipSync(fs.readFileSync(`${root}/snapshot-inputs/UK/sources/uk_allego_uk_pcpr_v9.json.gz`)));
const audit=JSON.parse(fs.readFileSync(`${root}/snapshot-inputs/UK/reports/allego_uk-pcpr-validation-latest.json`));
const adapter=require(`${root}/runtime/assets/v9/adapters/uk-pcpr.js`);
const result=adapter.normalizePayload(doc,audit,source);
const connectors=result.stations.flatMap(s=>s.evses.flatMap(e=>e.connectors));
const offers=result.stations.flatMap(s=>s.offers);
assert.equal(result.stations.length,77);
assert.equal(connectors.length,240);
assert.equal(offers.length,240);
assert.equal(new Set(offers.map(o=>o.metadata.sourceTariffId)).size,39);
assert.ok(connectors.some(c=>c.kind==='AC'&&c.powerKw>=22&&c.powerKw<=23&&c.powerSource==='derived_from_ocpi_voltage_current'));
assert.ok(connectors.some(c=>c.kind==='DC'&&c.powerKw>0));
assert.ok(offers.every(o=>o.connectorIds.length===1&&o.evseIds.length===1&&o.minPowerKw>0));
console.log(JSON.stringify({pass:true,stations:77,connectors:240,pricedOffers:240,tariffs:39}));
