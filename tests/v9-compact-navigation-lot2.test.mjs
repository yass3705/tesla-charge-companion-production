import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const ui=require('../v9-production-shell/bridge.js');
assert.equal(typeof ui.installFloatingNavigation,'function');
const handlers={};
const button=id=>({id,addEventListener:(type,fn)=>{handlers[id+':'+type]=fn;}});
const filters=button('v9JumpFilters'),top=button('v9JumpTop');
const nav={id:null,innerHTML:'',setAttribute(){},querySelector(selector){return selector==='#v9JumpFilters'?filters:top;}};
const panel={open:false,scrollIntoView(){handlers.scrolled=true;},querySelector(){return{focus(){handlers.focused=true;}}}};
const compare={closest(){return{classList:{contains:()=>true}};}};
const doc={getElementById(id){return id==='compare'?compare:null;},createElement(){return nav;},body:{appendChild(node){handlers.attached=node;}},querySelector(selector){return selector==='#compare .v9-filter-group'?panel:null;}};
let scrolledTo=null;
ui.installFloatingNavigation({document:doc,scrollTo(value){scrolledTo=value;}});
assert.equal(handlers.attached,nav);
assert.equal(typeof handlers['v9JumpFilters:click'],'function');
assert.equal(typeof handlers['v9JumpTop:click'],'function');
handlers['v9JumpFilters:click']();
assert.equal(panel.open,true);
assert.equal(handlers.scrolled,true);
assert.equal(handlers.focused,true);
handlers['v9JumpTop:click']();
assert.deepEqual(scrolledTo,{top:0,behavior:'smooth'});
console.log('V9 Lot 2 floating navigation OK');
